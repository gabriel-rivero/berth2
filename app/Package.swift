// swift-tools-version:6.0
// Berth app shell. Build with `make bootstrap && make build` (see docs/05-build.md).
//
// Two native dependencies:
//   - GhosttyKit.xcframework: produced by the pinned Ghostty submodule (not committed).
//   - libberth_ffi.a: the Rust core, built by `make core-lib` (not committed).
// `swift build` fails until both exist.

import Foundation
import PackageDescription

let packageDir = URL(fileURLWithPath: #filePath).deletingLastPathComponent()

// Rust targets the host architecture; the app ships Apple Silicon first.
#if arch(arm64)
let rustTriple = "aarch64-apple-darwin"
#else
let rustTriple = "x86_64-apple-darwin"
#endif
let coreLibDir = packageDir
    .appendingPathComponent("../core/target/\(rustTriple)/release")
    .standardizedFileURL.path

let package = Package(
    name: "Berth",
    platforms: [.macOS(.v14)],
    products: [
        .executable(name: "Berth", targets: ["Berth"])
    ],
    targets: [
        .binaryTarget(
            name: "GhosttyKit",
            path: "../vendor/ghostty/macos/GhosttyKit.xcframework"
        ),
        // Generated by uniffi-bindgen (scripts/bindings.sh). Headers only: the
        // implementation is the Rust static library.
        .target(
            name: "berth_ffiFFI",
            path: "Sources/berth_ffiFFI"
        ),
        // Generated UniFFI Swift bindings, kept in their own target so the
        // checked-in output stays visually separate from hand-written code.
        .target(
            name: "BerthCore",
            dependencies: ["berth_ffiFFI"],
            path: "Sources/BerthCore"
        ),
        .executableTarget(
            name: "Berth",
            dependencies: ["GhosttyKit", "BerthCore"],
            path: "Sources/Berth",
            // GhosttyKit is a bare static archive: it carries no link settings of
            // its own, so the C++ runtime its shader compiler needs and the
            // Carbon TIS symbols it uses for keyboard layouts must be named here.
            // libberth_ffi.a is likewise a bare archive; its path is host-specific
            // so it cannot be a `.linkedLibrary` name alone.
            linkerSettings: [
                .unsafeFlags(["-L\(coreLibDir)"]),
                .linkedLibrary("berth_ffi"),
                .linkedLibrary("c++"),
                .linkedFramework("Carbon"),
            ]
        ),
        .testTarget(
            name: "BerthTests",
            dependencies: ["Berth"],
            path: "Tests/BerthTests"
        ),
    ]
)
